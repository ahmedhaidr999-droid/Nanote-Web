export const DICTS: Record<Lang, Dict> = { en, ar };

export function translate(lang: Lang, key: string, enFallback?: string, arFallback?: string): string {
  const d = DICTS[lang];
  const hit = d[key] ?? DICTS.en[key];
  if (hit) return hit;
  if (enFallback || arFallback) {
    // register on-demand fallbacks in BOTH dictionaries so a key first used in
    // one language still resolves when the user switches languages later
    if (enFallback && DICTS.en[key] == null) DICTS.en[key] = enFallback;
    if (arFallback && DICTS.ar[key] == null) DICTS.ar[key] = arFallback;
    return (lang === 'ar' ? DICTS.ar[key] : DICTS.en[key]) ?? key;
  }
  return key;
}

/** Substitute {placeholders} */
export function fmt(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}
