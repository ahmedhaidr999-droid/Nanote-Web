  String _lookup(String q) {
    final lower = q.trim().toLowerCase();
    if (lower.isEmpty) return '';
    final direct = _dict[q.trim()] ?? _dict[lower];
    if (direct != null) return direct;
    for (final e in _dict.entries) {
      if (e.value.toLowerCase() == lower) return e.key;
    }
    return '';
  }

  /// [source] is 'auto', 'ar' or 'en'; target is 'ar' or 'en'.
  Future<TranslateResult> translate(String text, String source, String target) async {
    text = text.trim();
    if (text.isEmpty) return const TranslateResult('', true, 'noop');

    final offline = _lookup(text);
    try {
      _client ??= HttpClient()..connectionTimeout = const Duration(seconds: 8);
      final uri = Uri.parse('https://api.mymemory.translated.net/get')
          .replace(queryParameters: {
        'q': text,
        'langpair': '${source == 'auto' ? 'ar' : source}|$target',
      });
      final req = await _client!.getUrl(uri);
      final res = await req.close();
      if (res.statusCode != 200) {
        throw HttpException('status ${res.statusCode}');
      }
      final body = await utf8.decoder.bind(res).join();
      final data = jsonDecode(body);
      String? out;
      if (data is Map<String, dynamic>) {
        final rd = data['responseData'];
        if (rd is Map<String, dynamic>) {
          final t = rd['translatedText'];
          if (t is String) out = t;
        }
      }
      if (out is String && out.trim().isNotEmpty &&
          !_looksLikeError(out)) {
        return TranslateResult(out, true, 'MyMemory');
      }
      throw const HttpException('empty');
    } catch (_) {
      if (offline.isNotEmpty) {
        return TranslateResult(offline, false, 'dict');
      }
      throw const TranslateFailed();
    }
  }

  static bool _looksLikeError(String s) =>
      s.contains('MYMEMORY WARNING') || s.contains('QUERY LENGTH LIMIT');

  static Uri googleTranslateUrl(String text, String source, String target) =>
      Uri.parse('https://translate.google.com/?sl='
          '${source == 'auto' ? 'auto' : source}&tl=$target&text='
          '${Uri.encodeComponent(text)}&op=translate');

  /// "Ask AI" launcher — Gemini share-intent style prompt.
  static Uri askAiUrl(String text) => Uri.parse(
      'https://g.co/gemini/share?prompt=${Uri.encodeComponent(text)}');

  void dispose() {
    _client?.close();
  }
}

class TranslateFailed implements Exception {
  const TranslateFailed();
  @override
  String toString() => 'translation failed (offline & no dictionary match)';
}

/// Resolve target/source langs from settings + hint text script.
(String source, String target) resolveLangPair(String text, AppSettings s) {
  final hasArabic = RegExp(r'[\u0600-\u06FF]').hasMatch(text);
  if (hasArabic) return ('ar', 'en');
  return ('en', 'ar');
}
